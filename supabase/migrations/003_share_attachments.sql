-- Upgrade an EXISTING database: supporting files sent with a publication. Run once in the Supabase SQL Editor.
-- (The app also creates this table itself on start.)
create table if not exists public.share_attachments (
    id           integer generated by default as identity primary key,
    document_id  integer references public.documents (id),
    share_id     integer references public.document_shares (id),
    filename     varchar(255),
    storage_key  varchar(500) not null,
    checksum     varchar(64),
    size         integer,
    uploaded_by  integer references public.profiles (id),
    created_at   timestamptz default now()
);
create index if not exists ix_share_attachments_document on public.share_attachments (document_id);
create index if not exists ix_share_attachments_share    on public.share_attachments (share_id);
alter table public.share_attachments enable row level security;
revoke all on public.share_attachments from anon, authenticated;
